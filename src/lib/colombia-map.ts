// Normalize a department name string from DB to a department ID
export function normDeptoId(raw: string): string {
  const s = raw.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
  if (s.includes('guajira')) return 'la_guajira';
  if (s.includes('atlantico')) return 'atlantico';
  if (s.includes('magdalena')) return 'magdalena';
  if (s.includes('bolivar')) return 'bolivar';
  if (s.includes('sucre')) return 'sucre';
  if (s.includes('cordoba')) return 'cordoba';
  if (s.includes('cesar')) return 'cesar';
  if (s.includes('norte') && s.includes('santander')) return 'norte_santander';
  if (s.includes('santander')) return 'santander';
  if (s.includes('boyaca')) return 'boyaca';
  if (s.includes('arauca')) return 'arauca';
  if (s.includes('vichada')) return 'vichada';
  if (s.includes('antioquia')) return 'antioquia';
  if (s.includes('choco')) return 'choco';
  if (s.includes('caldas')) return 'caldas';
  if (s.includes('risaralda')) return 'risaralda';
  if (s.includes('quindio')) return 'quindio';
  if (s.includes('bogota') || s.includes('d.c') || s.includes('capital')) return 'bogota';
  if (s.includes('cundinamarca')) return 'cundinamarca';
  if (s.includes('casanare')) return 'casanare';
  if (s.includes('meta')) return 'meta';
  if (s.includes('tolima')) return 'tolima';
  if (s.includes('valle')) return 'valle';
  if (s.includes('huila')) return 'huila';
  if (s.includes('guainia')) return 'guainia';
  if (s.includes('guaviare')) return 'guaviare';
  if (s.includes('caqueta')) return 'caqueta';
  if (s.includes('putumayo')) return 'putumayo';
  if (s.includes('vaupes')) return 'vaupes';
  if (s.includes('cauca')) return 'cauca';
  if (s.includes('narino')) return 'narino';
  if (s.includes('amazonas')) return 'amazonas';
  return '';
}
